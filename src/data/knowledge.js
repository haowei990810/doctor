// 非诊断性行动分级：只根据明确的症状/情境给出下一步，不计算“患病概率”。
export function evaluate(selectedIds = []) {
  const selected = symptomChecklist
    .flatMap((group) => group.items)
    .filter((item) => selectedIds.includes(item.id))

  if (selected.some((item) => item.triage === 'emergency')) {
    return {
      level: 'emergency',
      title: '出现急症信号',
      color: '#f2555f',
      actionLabel: '急诊',
      desc: '你勾选了可能危及呼吸、意识、循环或神经功能的信号。请立即拨打 120 或前往急诊，并主动说明蜱叮咬或野外暴露史。',
      advice: ['立即拨打 120 或前往急诊', '不要自行驾车或独自等待', '记录叮咬、移除和症状出现时间', '不要因自行用药延误急救']
    }
  }
  if (selected.some((item) => item.triage === 'urgent')) {
    return {
      level: 'urgent',
      title: '建议尽快就医',
      color: '#f6a13d',
      actionLabel: '就医',
      desc: '你勾选了需要专业评估的症状或处理困难。请尽快到正规医疗机构就诊，说明蜱叮咬、野外活动、动物接触及症状出现时间。',
      advice: ['尽快就诊并说明暴露史', '记录体温与症状变化', '给皮疹拍照并观察是否扩大', '不要根据虫体检测自行决定用药']
    }
  }
  return {
    level: 'observe',
    title: '暂无明确警示信号',
    color: '#59cf9a',
    actionLabel: '观察',
    desc: '目前勾选内容未提示明确急症或就医信号。这不代表“没有感染”或可排除疾病；请规范移除和清洁，重点观察 2 周，之后数周仍留意发热、扩大皮疹等变化。',
    advice: ['记录叮咬与移除日期', '重点观察 2 周，之后数周继续留意', '出现发热、扩大皮疹或全身不适尽快就医', '不要自行预防性服用抗生素']
  }
}
