// 结果评估分级
export function evaluate(score, hasKey) {
  if (hasKey || score >= 7) {
    return {
      level: 'high',
      title: '建议立即就医',
      color: '#f2555f',
      desc: '你勾选了危险信号或症状较多，存在蜱媒疾病或重症风险，请尽快前往医院（感染科/急诊），并主动告知医生蜱虫叮咬史。',
      advice: ['立即就医并说明叮咬史', '保存好取出的蜱虫供医生识别', '记录发病与叮咬时间', '避免自行用药延误']
    }
  }
  if (score >= 3) {
    return {
      level: 'mid',
      title: '密切观察，及时就诊',
      color: '#f6a13d',
      desc: '目前症状需要重视。请在叮咬后 2 周内密切观察体温与身体状况，一旦症状加重应尽快就医。',
      advice: ['每日监测体温', '观察红斑是否扩大', '症状加重立即就医', '按正确步骤处理伤口']
    }
  }
  return {
    level: 'low',
    title: '暂时风险较低',
    color: '#59cf9a',
    desc: '目前未见明显危险信号。仍需按正确方法取出蜱虫、消毒伤口，并在 2～4 周内持续观察是否出现发热、皮疹等症状。',
    advice: ['规范处理伤口并消毒', '持续观察 2～4 周', '出现不适随时就医', '做好后续防护']
  }
}
